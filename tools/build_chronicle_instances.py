"""The dungeons and raids the chronicle's instance window knows: their bosses (the dungeon journal's, shared/assets/db/
dungeons.json) and the maps of their floors (shared/assets/world/floors.json, tools/build_dungeon_floors.py).

Output: platform/lib/chronicle-instances.data.ts. Run after either source changes:  python tools/build_chronicle_instances.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DUNGEONS = ROOT / "shared" / "assets" / "db" / "dungeons.json"
FLOORS = ROOT / "shared" / "assets" / "world" / "floors.json"
OUT = ROOT / "platform" / "lib" / "chronicle-instances.data.ts"

# journal rows that are not a boss of their own
NOT_A_BOSS = ("trash", "quest", "chest", "world drop")


def main() -> None:
    dungeons = json.loads(DUNGEONS.read_text(encoding="utf8"))["entries"]
    floors = json.loads(FLOORS.read_text(encoding="utf8"))
    out = []
    for d in dungeons:
        bosses = []
        for b in d.get("bosses") or []:
            name = (b.get("name") or "").strip()
            low = name.lower()
            if not name or any(word in low for word in NOT_A_BOSS) or low.startswith(("all ", "tier ")) or low.endswith(" sets"):
                continue
            boss = {"name": name}
            if isinstance(b.get("npc"), int):
                boss["npc"] = b["npc"]
            if b.get("rare"):
                boss["rare"] = True
            bosses.append(boss)
        map_id = floors["keys"].get(d["key"])
        entry = {"key": d["key"], "name": d["name"], "type": "raid" if d.get("type") == "raid" else "dungeon", "bosses": bosses}
        if d.get("group"):
            entry["group"] = d["group"]
        if isinstance(d.get("players"), int):
            entry["players"] = d["players"]
        if isinstance(d.get("lvl"), list) and len(d["lvl"]) == 2:
            entry["lvl"] = d["lvl"]
        if map_id is not None:
            entry["mapId"] = map_id
            entry["floors"] = [{"img": f["img"], **({"name": f["name"]} if f.get("name") else {})} for f in floors["maps"].get(str(map_id), [])]
        out.append(entry)
    text = (
        "// Generated by tools/build_chronicle_instances.py from shared/assets/db/dungeons.json and shared/assets/world/floors.json.\n"
        "// Do not edit by hand.\n"
        "export type InstanceBoss = { name: string; npc?: number; rare?: boolean };\n"
        "export type InstanceFloor = { img: string; name?: string };\n"
        "export type InstanceInfo = { key: string; name: string; type: \"dungeon\" | \"raid\"; group?: string; players?: number; lvl?: [number, number]; "
        "mapId?: number; floors?: InstanceFloor[]; bosses: InstanceBoss[] };\n"
        f"export const INSTANCES: InstanceInfo[] = {json.dumps(out, ensure_ascii=False)};\n"
    )
    OUT.write_text(text, encoding="utf8")
    print(f"{len(out)} instances, {sum(len(e['bosses']) for e in out)} bosses, {sum(1 for e in out if e.get('floors'))} with floor maps -> {OUT}")


if __name__ == "__main__":
    main()
