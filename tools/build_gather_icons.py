"""The picture of each gathering resource: the file ID of the game's own item icon (an herb's leaf, an ore, a clam), written to
addon/Evertally_Map/GatherIcons.lua as numbers only. No art is shipped: the game draws the file it is told by ID.

Item names and icon file IDs come from the project's item table (shared/assets/db/search.json, the Forever client's items) with the
client's Item table (shared/sources/Item-*.csv) behind it. A node's name is turned into the item it yields: "Copper Vein" -> "Copper Ore".
Run from the project root: python tools/build_gather_icons.py
"""
from pathlib import Path
import csv
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SEARCH = ROOT / "shared" / "assets" / "db" / "search.json"
CSV_FILE = next((ROOT / "shared" / "sources").glob("Item-*.csv"))
LAYER_DATA = ROOT / "addon" / "Evertally_Map" / "LayerData.lua"
OUT = ROOT / "addon" / "Evertally_Map" / "GatherIcons.lua"

# nodes whose item is not simply their name
ALIAS = {
    "Small Thorium Vein": "Thorium Ore", "Rich Thorium Vein": "Thorium Ore", "Lesser Bloodstone Deposit": "Lesser Bloodstone Ore",
    "Greater Moonstone Formation": "Greater Moonstone", "Fool's Gold Vein": "Fool's Gold Dust", "Incendicite Mineral Vein": "Incendicite Ore",
    "Giant Clam": "Thick-shelled Clam", "Sagefish School": "Raw Sagefish", "Oily Blackmouth School": "Oily Blackmouth",
    "Un'Goro Soil": "Un'Goro Soil",
    # no item of their own: the nearest thing the game has a picture of
    "Chunk of Amber": "Blood Amber", "Large Chunk of Amber": "Blood Amber",
    "Small Obsidian Chunk": "Dark Iron Ore", "Large Obsidian Chunk": "Dark Iron Ore",
    "Floating Debris": "Fishing Pole", "Floating Wreckage": "Fishing Pole",
    "Battered Footlocker": "Small Chest", "Battered chest": "Small Chest", "Dented Footlocker": "Small Chest", "Mossy Footlocker": "Small Chest",
    "Waterlogged Footlocker": "Small Chest", "Scarlet Footlocker": "Small Locked Chest", "Solid chest": "Small Locked Chest",
    "Large solid chest": "Small Locked Chest", "Buccaneer's Strongbox": "Mok'Morokk's Strongbox", "Practice Lockbox": "Iron Lockbox",
}


def main():
    items = json.loads(SEARCH.read_text(encoding="utf8"))["items"]
    by_name = {}
    for row in items:
        by_name.setdefault(row[1].lower(), row)
    csv_icons = {}
    with CSV_FILE.open(encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            csv_icons[int(row["ID"])] = int(row["IconFileDataID"])

    def icon_of(name):
        row = by_name.get(name.lower())
        if not row:
            return None, None
        return row[0], row[9] or csv_icons.get(row[0])

    nodes = re.findall(r'\{"([a-z]+:[a-z_]+)","([^"]+)","([a-z]+)"', LAYER_DATA.read_text(encoding="utf8"))
    out, report = {}, []
    for key, name, kind in nodes:
        candidates = [ALIAS.get(name), name]
        if kind == "ore":
            candidates.append(re.sub(r" (Vein|Deposit|Formation)$", " Ore", name))
        found = None
        for candidate in candidates:
            if candidate:
                item, icon = icon_of(candidate)
                if icon:
                    found = (candidate, item, icon)
                    break
        if found:
            out[key] = found[2]
            if found[0] != name:
                report.append(f"{key}: {name} -> {found[0]} (item {found[1]})")
        else:
            report.append(f"{key}: {name} -> NO ICON")
    kinds = {"herb": "Peacebloom", "ore": "Copper Ore", "fishing": "Raw Sagefish", "container": "Small Chest"}
    kind_icons = {kind: icon_of(item)[1] for kind, item in kinds.items()}
    lines = [
        "-- The picture of each gathering resource: the file ID of the game's own item icon (an herb's leaf, an ore, a clam). Numbers only:",
        "-- the game draws the file it is told by ID, no art is shipped. Generated by tools/build_gather_icons.py; regenerate rather than edit.",
        "local _, M = ...",
        "M.gatherIcons = {",
    ]
    for key in sorted(out):
        lines.append(f'    ["{key}"] = {out[key]},')
    lines.append("}")
    lines.append("-- for a resource with no picture of its own, one for its kind")
    lines.append("M.gatherKindIcons = {" + ", ".join(f"{kind} = {icon}" for kind, icon in sorted(kind_icons.items())) + "}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")
    print(f"{len(out)} of {len(nodes)} resources have an icon")
    for line in report:
        print("  ", line)


if __name__ == "__main__":
    main()
