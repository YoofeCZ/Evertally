"""Write the item level table the website server uses for the leaderboard's average item level.

Reads the website's own item index (platform/public/media/db/search.json, built by tools/build_db.py;
source and licence in THIRD_PARTY.md) and keeps armour and weapons with a known item level. Local files
only, no network.

Output: platform/lib/item-levels.data.ts  (one string; each entry is "<id base36>.<ilvl base36>", a
trailing "*" marks a two-handed weapon; entries are separated by ",")
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "platform" / "public" / "media" / "db" / "search.json"
OUT = ROOT / "platform" / "lib" / "item-levels.data.ts"


def b36(n: int) -> str:
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out = ""
    while True:
        n, r = divmod(n, 36)
        out = digits[r] + out
        if n == 0:
            return out


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    cats, slots = data["cats"], data["slots"]
    two_hand = slots.index("Two-Hand")
    keep_cats = {cats.index("Armor"), cats.index("Weapon")}
    entries = []
    for row in data["items"]:
        item_id, ilvl, cat, slot = row[0], row[3], row[5], row[6]
        if not isinstance(ilvl, int) or ilvl <= 0:
            continue
        # rows without a category are kept: they may be gear the index knows only briefly
        if cat is not None and cat >= 0 and cat < len(cats) and cat not in keep_cats and slot < 0:
            continue
        entries.append(f"{b36(item_id)}.{b36(ilvl)}{'*' if slot == two_hand else ''}")
    entries.sort()
    text = (
        "// Generated by tools/build_item_levels.py from public/media/db/search.json. Do not edit.\n"
        f"// {len(entries)} items: \"<id base36>.<item level base36>\", \"*\" = two-handed weapon.\n"
        f"export const ITEM_LEVELS = \"{','.join(entries)}\";\n"
    )
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(entries)} items, {len(text)} bytes")


if __name__ == "__main__":
    main()
