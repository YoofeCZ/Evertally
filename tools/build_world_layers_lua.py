"""Bake existing gathering locations and instance entrances into the load-on-demand game map.

Run after build_gather.py / build_db.py. No network or player data is used.
Sources and rights retain the provenance of those inputs (see THIRD_PARTY.md).
"""
from __future__ import annotations

import json
from pathlib import Path

from build_map_lua import lua

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / "platform/public/media"
OUT = ROOT / "addon/Evertally_Map/LayerData.lua"


def main() -> None:
    gather = json.loads((MEDIA / "gather/gather.json").read_text(encoding="utf8"))
    dungeons = json.loads((MEDIA / "db/dungeons.json").read_text(encoding="utf8"))["entries"]
    world = json.loads((MEDIA / "world/world.json").read_text(encoding="utf8"))["maps"]
    maps: dict[int, list] = {}
    nodes = []
    for i, node in enumerate(gather["nodes"], 1):
        nodes.append([node["key"], node["name"], node["type"], node.get("skill")])
        for map_id, points in sorted(gather["points"].get(node["key"], {}).items(), key=lambda item: int(item[0])):
            if any(not isinstance(n, int) or n < 0 or n > 1000 for n in points) or len(points) % 2:
                raise ValueError(f"Invalid points for {node['key']} map {map_id}")
            maps.setdefault(int(map_id), []).append([i, points])
    instances = []
    for item in dungeons:
        entry = item.get("entrance")
        place = world.get(entry["zone"]) if entry else None
        if entry and place and not (0 <= entry["x"] <= 100 and 0 <= entry["y"] <= 100):
            raise ValueError(f"Invalid instance entrance: {item['key']}")
        instances.append({"key": item["key"], "name": item["name"], "kind": item["type"], "level": item.get("lvl"),
                          "players": item["players"], "map": place["ui"] if place else None,
                          "x": entry["x"] / 100 if place else None, "y": entry["y"] / 100 if place else None,
                          "hint": entry.get("hint", "") if entry else ""})
    data = {"schema": 1, "nodes": nodes, "gather": maps, "instances": instances}
    header = ("-- Generated by tools/build_world_layers_lua.py; do not edit by hand.\n"
              "-- Gathering: GatherLite coordinates generated from Wowhead listings; entrances: existing Evertally reference DB.\n"
              "-- Reference locations are possible spawns, never a claim that a resource is currently available. See THIRD_PARTY.md.\n"
              "local _, M = ...\n")
    OUT.write_text(header + "M.layerData = " + lua(data) + "\n", encoding="utf8")
    count = sum(len(group[1]) // 2 for groups in maps.values() for group in groups)
    placed = sum(item["map"] is not None for item in instances)
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size // 1024} KiB, {len(nodes)} resources / {count} reference points, {placed}/{len(instances)} entrances")


if __name__ == "__main__":
    main()
