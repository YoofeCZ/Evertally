"""Build the unambiguous NPC-name lookup for old chronicles without creature IDs.

Uses the same licensed reference facts as the existing NPC database, never player data.
"""
from collections import defaultdict
import json
import gzip
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = json.loads((ROOT / "platform/public/media/db/search.json").read_text(encoding="utf8"))["npcs"]
names = defaultdict(list)
for row in rows:
    names[row[1].casefold()].append(row[0])
unique = {name: ids[0] for name, ids in sorted(names.items()) if len(ids) == 1}
source = ROOT / "shared/sources/ClassicDB_1_12_1_z2815.sql.gz"
reference = {row[0]: row[1] for row in rows}
models = {}
pattern = re.compile(r"\((\d+),'((?:[^'\\]|\\.)*)',(?:NULL|'(?:[^'\\]|\\.)*'),\d+,\d+,(\d+),(\d+),(\d+),(\d+),")
with gzip.open(source, "rt", encoding="utf8") as sql:
    for line in sql:
        if not line.startswith("INSERT INTO `creature_template` VALUES "):
            continue
        for match in pattern.finditer(line):
            npc = int(match[1])
            name = match[2].replace("\\'", "'").replace("\\\\", "\\")
            display = next((int(value) for value in match.groups()[2:] if int(value) > 0), 0)
            if display and reference.get(npc) == name:
                models[npc] = [name, display]
target = ROOT / "platform/lib/chronicle-npcs.data.ts"
target.write_text('// Generated by tools/build_chronicle_npcs.py from the existing NPC reference database.\n'
                  '// Only unique names are resolved; ambiguous names need an observed creature ID. See THIRD_PARTY.md.\n'
                  '// Model facts: CMaNGOS ClassicDB z2815, SHA256 ' + hashlib.sha256(source.read_bytes()).hexdigest() + '.\n'
                  'export const CHRONICLE_NPCS: Readonly<Record<string, number>> = '
                  + json.dumps(unique, ensure_ascii=False, separators=(",", ":")) + ';\n'
                  + 'export const CHRONICLE_NPC_MODELS: Readonly<Record<number, readonly [name: string, displayId: number]>> = '
                  + json.dumps(models, ensure_ascii=False, separators=(",", ":")) + ';\n', encoding="utf8")
print(f"Wrote {len(unique)} unique NPC names and {len(models)} model references ({target.stat().st_size} bytes)")
