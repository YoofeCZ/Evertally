"""Bake the journey planner's data into a Lua file for the in-game map add-on (Evertally_Map).

The website plans journeys in TypeScript from platform/public/media/world/{travel,flights,world}.json. The game cannot read
those, so this writes the same numbers as one Lua table, and the Lua planner (Evertally_Map/Planner.lua) runs the same search.
Run after tools/build_travel_data.py and tools/build_map_data.py:

    python tools/build_map_lua.py

Source of the travel numbers is Shortest Path Forever (GPL-3.0), see THIRD_PARTY.md: the add-on folder that carries this file
is therefore distributed under GPL-3.0 as well.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORLD = ROOT / "platform" / "public" / "media" / "world"
OUT = ROOT / "addon" / "Evertally_Map" / "Data.lua"


def lua(value, indent=0) -> str:
    pad = "    " * indent
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)  # shortest exact form: the yards coefficients are around 1e-5 and must not be rounded
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        if all(not isinstance(v, (list, dict)) for v in value):
            return "{" + ",".join(lua(v) for v in value) + "}"
        return "{\n" + "".join(f"{pad}    {lua(v, indent + 1)},\n" for v in value) + pad + "}"
    if isinstance(value, dict):
        def key(k):
            return f"[{k}]" if isinstance(k, int) else (k if k.isidentifier() else f'["{k}"]')
        return "{\n" + "".join(f"{pad}    {key(k)}={lua(v, indent + 1)},\n" for k, v in value.items()) + pad + "}"
    raise TypeError(type(value))


def main() -> int:
    travel = json.loads((WORLD / "travel.json").read_text(encoding="utf8"))
    flights = json.loads((WORLD / "flights.json").read_text(encoding="utf8"))
    world = json.loads((WORLD / "world.json").read_text(encoding="utf8"))

    hubs = {}
    for hub_id, hub in travel["hubs"].items():
        hubs[hub_id] = [hub["c"], hub["x"], hub["y"], hub.get("u"), hub.get("v"), hub.get("n", ""), hub.get("f", "")]

    walks: dict[str, list] = {}
    for table in travel["walks"].values():
        for pair, cost in table.items():
            if cost:
                walks[pair] = [cost[0], cost[1]]

    maps = {}
    codes = {"zone": 1, "city": 2, "continent": 3, "world": 4}
    for key, entry in world["maps"].items():
        left, right, top, bottom = entry["rect"]
        maps[entry["ui"]] = [left, right, top, bottom, codes[entry["kind"]], key]

    data = {
        "yards": {int(c): [v[4], v[5], v[6], v[7]] for c, v in travel["yards"].items()},
        "hubs": hubs,
        "walks": walks,
        "routes": [[r["id"], r["k"], r.get("f", ""), r["p"], [list(stop) for stop in r["stops"]]] for r in travel["routes"]],
        "portals": [[p["n"], p["k"], p["a"], p["b"], p["s"]] for p in travel["portals"]],
        "landmasses": [[m["c"], m["x0"], m["x1"], m["y0"], m["y1"]] for m in travel["landmasses"]],
        "flights": [[p["a"], p["b"], p["s"]] for p in flights["paths"]],
        "flightSide": {int(i): node.get("f", "") for i, node in flights["nodes"].items()},
        "maps": maps,
    }
    header = (
        "-- Generated by tools/build_map_lua.py from platform/public/media/world/*.json. Do not edit by hand.\n"
        "-- Travel numbers: Shortest Path Forever (GPL-3.0); map rectangles: wago.tools UiMap tables. See THIRD_PARTY.md.\n"
        "local _, M = ...\n"
        "-- yards[c]={au,bu,av,bv}: (u,v) on Azeroth's map -> game yards x=(v-av)/bv, y=(u-au)/bu (x north, y west)\n"
        "-- hubs[id]={continent,x,y,u,v,name,faction}; walks['a b']={yards a->b, yards b->a}; routes={id,kind,faction,period,{{dock,arrive,depart}..}}\n"
        "-- portals={name,kind,from,to,seconds}; landmasses={continent,x0,x1,y0,y1}; flights={from,to,seconds}\n"
        "-- maps[uiMapID]={left,right,top,bottom,1 zone|2 city|3 continent|4 world,key}: the rectangle of a map on Azeroth's map\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "M.data = " + lua(data) + "\n", encoding="utf8")
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size / 1024:.0f} KiB; {len(hubs)} hubs, {len(walks)} walks, {len(data['routes'])} routes, "
          f"{len(data['portals'])} portals, {len(data['flights'])} flights, {len(maps)} maps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
