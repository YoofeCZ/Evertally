"""Pack the exact web EVWM v1 terrain into Lua without expanding millions of cells.

Source mask: Shortest Path Forever/GatherLite terrain bake, GPL-3.0-or-later.
One ASCII base64 symbol stores three 2-bit cells. The Lua runtime reads cells in place.
Run after build_walkmask.py. No player data or network access.
"""
from pathlib import Path
import hashlib
import struct
import zlib

ROOT=Path(__file__).resolve().parents[1]
ALPHABET='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'


def main():
    source=ROOT/'platform/public/media/world/walk.bin'
    blob=source.read_bytes()
    if blob[:5]!=b'EVWM\x01':
        raise ValueError('Expected EVWM v1')
    lines=['local _, M = ...', '-- Generated by tools/build_terrain_lua.py; do not edit.',
           '-- Terrain: Shortest Path Forever/GatherLite, GPL-3.0-or-later.',
           '-- Same 16-yard mask as the website; cliffs and interior floors are not modelled.',
           f'-- walk.bin SHA-256: {hashlib.sha256(blob).hexdigest()}', 'M.terrainMaps = {']
    at,total=6,0
    for _ in range(blob[5]):
        map_id,x0,y0,cell,nx,ny,length=struct.unpack_from('<hfffHHI',blob,at);at+=22
        raw=zlib.decompress(blob[at:at+length]);at+=length
        if len(raw)!=nx*ny or any(value>2 for value in raw):
            raise ValueError(f'Invalid terrain {map_id}')
        padded=raw+bytes((-len(raw))%3)
        packed=''.join(ALPHABET[padded[i]*16+padded[i+1]*4+padded[i+2]] for i in range(0,len(padded),3))
        # Validate the actual generated bytes, including the partial final group.
        lookup={c:i for i,c in enumerate(ALPHABET)}
        check=bytes((lookup[packed[i//3]]//(16,4,1)[i%3])%4 for i in range(len(raw)))
        if check!=raw:raise ValueError('Terrain packing roundtrip failed')
        lines.append(f'  [{map_id}] = {{id={map_id}, x0={x0:.12g}, y0={y0:.12g}, cell={cell:.12g}, nx={nx}, ny={ny}, data=table.concat({{')
        lines.extend('    "'+packed[i:i+2048]+'",' for i in range(0,len(packed),2048))
        lines.append('  })},')
        total+=len(raw)
    if at!=len(blob):raise ValueError('Unexpected EVWM trailing bytes')
    lines.append('}')
    target=ROOT/'addon/Evertally_Map/TerrainData.lua'
    target.write_text('\n'.join(lines)+'\n',encoding='utf8')
    print(f'{len(blob)} EVWM bytes -> {target.stat().st_size} Lua bytes; {total} exact cells; {blob[5]} maps')


if __name__=='__main__':main()
